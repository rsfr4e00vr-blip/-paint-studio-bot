const assert=require('node:assert/strict');
const fs=require('node:fs');
const mm=fs.readFileSync('./military_map.js','utf8');
const game=fs.readFileSync('./game.js','utf8');
const cities=fs.readFileSync('./city_sat.js','utf8');
assert.match(mm,/const landGrid=new Map\(\)/,'capture must build a local land-unit grid');
assert.match(mm,/landGrid\.get\(gx\+','\+gy\)/,'capture must inspect only adjacent spatial buckets');
assert.doesNotMatch(mm,/const contested=MM\.units\.some\(/,'quadratic full-army contested scan must be gone');
assert.match(mm,/Армия противника · гарнизон/,'war AI must create a starter garrison');
assert.match(mm,/Бронегруппа противника/,'war AI must create a starter armored group');
assert.match(game,/const TERRAIN_GRID=new WeakMap\(\)/,'terrain overlays must use a per-country spatial index');
assert.match(game,/TERRAIN_MAX=180/,'terrain SVG generation must be bounded');
assert.match(cities,/const CITY_CELL=24/,'city markers must use a spatial index');
assert.match(cities,/CITY_GRID\.get\(cx\+','\+cy\)/,'city rendering must query only visible spatial buckets');
console.log('OK: war capture, enemy initial force, terrain and city rendering are spatially bounded');