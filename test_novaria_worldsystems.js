const assert=require('assert');
global.window={};
require('./novaria_worldsystems.js');
const S={name:'Testland',year:1,month:0,money:10000,gdp:42000,pop:1000000,employment:90,steel:60,energy:70,food:70,regions:[{name:'Capital',pop:1000000,infra:80,industry:70}]};
window.NovaSystems.ensure(S);
assert.equal(S.regions[0].assets.length,6);
const asset=S.regions[0].assets[0];
asset.condition=50;
let r=window.NovaSystems.repairAsset(S,0,0);
assert.equal(r.ok,true);
assert(S.money<10000);
assert(S.novaria.recoveryBudget>0);
const before=asset.condition;
for(let i=0;i<4;i++)window.NovaSystems.tick(S);
assert(asset.condition>before);
assert(Array.isArray(asset.history));
assert(window.NovaSystems.setDoctrine(S,'defensive'));
assert.equal(S.novaria.doctrine,'defensive');
assert(window.NovaSystems.investAsset(S,'tech'));
assert(S.novaria.techRace>0);
assert(window.NovaSystems.crisisAsset(S,'energy'));
window.NovaSystems.tick(S);
assert(S.novaria.crises.length>0);
window.NovaSystems.aiPlan(S);
assert(S.novaria.aiMemory.Testland);
console.log('Novaria world systems: OK');
